export type IconName = keyof typeof TRACES;

/**
 * Une icône DÉCORATIVE par défaut : elle double un libellé déjà lisible, donc
 * elle est masquée aux lecteurs d'écran. Une icône seule — un bouton sans
 * texte — passe `label`, et devient alors une image nommée.
 */
export function Icon({
  name,
  size = 16,
  label,
  className,
}: {
  name: IconName;
  size?: number;
  label?: string;
  className?: string;
}) {
  const traces = TRACES[name];
  if (!traces) return null;
  return (
    <svg
      className={className ? `icon ${className}` : 'icon'}
      width={size}
      height={size}
      viewBox="0 0 16 16"
      fill="currentColor"
      focusable="false"
      {...(label ? { role: 'img', 'aria-label': label } : { 'aria-hidden': true })}
    >
      {traces.map((trace) => (
        <path key={trace.d} d={trace.d} {...(trace.evenOdd ? { fillRule: 'evenodd' } : {})} />
      ))}
    </svg>
  );
}

export default Icon;
